// After `next build`: write out/sw.js with every file of this build in its
// precache list, so the whole app works offline after the first visit.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const OUT = "out";
const BASE = process.env.GYM_BASE_PATH ?? "/gym";
const SKIP = [/^sw\.js$/, /^demos\//, /^404/, /\.unreadable/, /^\.nojekyll$/];

const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) walk(full);
    else files.push(path.relative(OUT, full).split(path.sep).join("/"));
  }
})(OUT);

const hash = createHash("sha256");
const urls = [];
for (const f of files.sort()) {
  if (SKIP.some((re) => re.test(f))) continue;
  hash.update(f).update(readFileSync(path.join(OUT, f)));
  urls.push(`${BASE}/${f}`);
}
const version = hash.digest("hex").slice(0, 12);

const sw = `// Generated by scripts/make-sw.mjs — build ${version}
const VERSION = ${JSON.stringify(version)};
const BASE = ${JSON.stringify(BASE)};
const CACHE = "gym-" + VERSION;
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) =>
      // One by one, so a single hiccup doesn't throw the whole cache away.
      Promise.all(PRECACHE.map((url) => cache.add(new Request(url, { cache: "reload" })).catch(() => {}))),
    ).then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("gym-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// The saved file for a page address: /gym/ -> /gym/index.html, /gym/log/ -> /gym/log/index.html
const pageKey = (url) => {
  const p = url.pathname.replace(/\\/index\\.html$/, "").replace(/\\.html$/, "").replace(/\\/+$/, "");
  return p + "/index.html";
};

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE)) return;

  if (req.mode === "navigate") {
    // Pages: fresh from the network when there's signal, the saved copy when there isn't.
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      try {
        const res = await Promise.race([
          fetch(req),
          new Promise((_, reject) => setTimeout(() => reject(new Error("slow")), 3500)),
        ]);
        if (res.ok && !res.redirected) cache.put(pageKey(url), res.clone());
        return res;
      } catch {
        return (await cache.match(pageKey(url))) || (await cache.match(BASE + "/index.html")) || Response.error();
      }
    })());
    return;
  }

  // Scripts, styles, fonts, images, page data: saved copy first (file names change with each build).
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(req, { ignoreSearch: true });
    if (hit) return hit;
    const res = await fetch(req);
    if (res.ok && url.pathname.startsWith(BASE + "/_next/static/")) cache.put(req, res.clone());
    return res;
  })());
});
`;
writeFileSync(path.join(OUT, "sw.js"), sw);
writeFileSync(path.join(OUT, ".nojekyll"), "");
console.log(`sw.js: ${urls.length} files precached, build ${version}`);
